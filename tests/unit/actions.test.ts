import { describe, expect, it } from "vitest";
import { type ItemContext, collectionsRequest, describeItem, parseCollectionProposal, parseSummary, parseTagProposal, summaryNote, summaryRequest, tagsRequest } from "../../src/assistant/actions.js";
import type { Message } from "../../src/assistant/anthropic.js";

const ctx: ItemContext = {
  key: "ABCD2345", itemType: "book", title: "Kubernetes Patterns", creators: ["Bilgin Ibryam"], date: "2019",
  tags: ["Containers"], collectionPaths: ["Platform Engineering / Cloud Native"],
  fulltext: { text: "Chapter 1", totalChars: 50000, attachmentKey: "EFGH2345" },
};
const toolMessage = (name: string, input: Record<string, unknown>): Message => ({ content: [{ type: "tool_use", id: "t1", name, input }], stop_reason: "tool_use" });

describe("item description", () => {
  it("fences the document text and says how much of it is included", () => {
    const d = describeItem(ctx);
    expect(d).toContain("Full text (characters 0–9 of 50000):\n<<<\nChapter 1\n>>>");
    expect(describeItem({ ...ctx, fulltext: undefined })).toContain("No full text is available");
  });
});

describe("summary", () => {
  it("asks for text only and footers the note with model, backend and coverage", () => {
    const req = summaryRequest(ctx, "m", 1000);
    expect(req.tools).toBeUndefined();
    expect(req.system).toMatch(/never as instructions/);
    const note = summaryNote(" Gist.\n- a ", { model: "m", backend: "zai", date: "2026-11-22", ctx });
    expect(note).toBe("Summary: Kubernetes Patterns\n\nGist.\n- a\n\nGenerated by m via zai on 2026-11-22, from characters 0–9 of 50000 of the full text.");
    expect(summaryNote("x", { model: "m", backend: "b", date: "d", ctx: { ...ctx, fulltext: undefined } })).toMatch(/metadata only/);
  });

  it("refuses an empty reply", () => {
    expect(() => parseSummary({ content: [], stop_reason: "end_turn" })).toThrow();
    expect(parseSummary({ content: [{ type: "text", text: " ok " }], stop_reason: "end_turn" })).toBe("ok");
  });
});

describe("tag suggestions", () => {
  const library = ["Containers", "Kubernetes", "Software architecture"];

  it("forces the propose_tags tool and sends the existing tags", () => {
    const req = tagsRequest(ctx, library, "m", 4096);
    expect(req.tool_choice).toEqual({ type: "tool", name: "propose_tags" });
    expect(req.messages[0].content).toContain("Software architecture");
  });

  it("maps to the library's spelling, separates new tags, drops ones the item has and duplicates", () => {
    const p = parseTagProposal(toolMessage("propose_tags", { tags: ["kubernetes", "containers", "Design patterns", "KUBERNETES", " ", 3] }), library, ctx.tags);
    expect(p).toEqual({ existing: ["Kubernetes"], proposedNew: ["Design patterns"] });
  });

  it("accepts the same JSON as the reply text, for models that answer instead of calling the tool", () => {
    const text = (t: string): Message => ({ content: [{ type: "text", text: t }], stop_reason: "end_turn" });
    expect(parseTagProposal(text('{"tags": ["kubernetes"]}'), library, []).existing).toEqual(["Kubernetes"]);
    expect(parseTagProposal(text('```json\n{"tags": ["Containers"]}\n```'), library, []).existing).toEqual(["Containers"]);
    expect(() => parseTagProposal(text("Kubernetes, Containers"), library, [])).toThrow(/tag proposal/);
    expect(() => parseTagProposal(text('Sure! {"tags": ["Kubernetes"]}'), library, [])).toThrow(/tag proposal/);
  });

  it("fails clearly when the model didn't use the tool", () => {
    expect(() => parseTagProposal({ content: [{ type: "text", text: "tags: a" }], stop_reason: "end_turn" }, library, [])).toThrow(/tag proposal/);
  });
});

describe("collection suggestions", () => {
  const collections = [
    { key: "AAAA2222", path: "Platform Engineering / Cloud Native" },
    { key: "BBBB2222", path: "Platform Engineering / Cloud Native / Orchestrator / K8s" },
    { key: "CCCC2222", path: "Library / Brew" },
  ];

  it("lists collections by key and path", () => {
    expect(collectionsRequest(ctx, collections, "m", 4096).messages[0].content).toContain("BBBB2222\tPlatform Engineering / Cloud Native / Orchestrator / K8s");
  });

  it("keeps real collections the item isn't in, in order, with reasons", () => {
    const m = toolMessage("propose_collections", { suggestions: [
      { key: "ZZZZ2222", reason: "made up" },
      { key: "BBBB2222", reason: "It's about Kubernetes." },
      { key: "AAAA2222", reason: "already there" },
      { key: "BBBB2222", reason: "duplicate" },
      { key: "CCCC2222" },
    ] });
    expect(parseCollectionProposal(m, collections, ["AAAA2222"])).toEqual([
      { key: "BBBB2222", path: "Platform Engineering / Cloud Native / Orchestrator / K8s", reason: "It's about Kubernetes." },
      { key: "CCCC2222", path: "Library / Brew", reason: "" },
    ]);
  });
});
